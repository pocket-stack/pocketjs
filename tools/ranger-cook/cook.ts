// tools/ranger-cook/cook.ts — M1 cook skeleton (hand-written).
//
// Entry: extract → raster → pack-manifest. In M1 the extract/raster stages
// are local-evidence only (no SWF needed): stable IDs come from ids.ts,
// pixel dimensions come from an IHDR scan of the local PNGs, and the
// variant/fighter/grid payload is the M1 snapshot carried by the current
// manifests (SWF-derived extraction is M2+ work). What M1 DOES enforce:
//
// - fail-hard scope: unknown or out-of-scope linkage IDs throw
//   CookScopeError via apps/ranger/scope.ts (never invent IDs);
// - manifest validation: stable-ID grammar, on-disk PNG existence,
//   frames == cols*rows, sprites/anim grid agreement, variant sheet
//   membership (failures throw CookError);
// - determinism: sorted keys, canonical JSON, exact provenance headers —
//   two runs over the same inputs are byte-identical (fixed point).
//
// The SWF is never required: `--swf <path>` / RANGER_SWF, when present, is
// only header-checked (FWS) and never copied into the repo or outputs.
// Outputs carry the logical ref `swf:fws6:root19f`, never a local path.
//
// Usage (bun or node with type stripping):
//   cook.ts [--app <dir>] [--linkage a,b,...] [--swf <path>] [--check]

