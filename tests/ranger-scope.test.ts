describe("ranger M0 cook scope gate (fail-hard) vs runtime gate (fail-soft)", () => {
  test("cook gate passes every in-scope LINKAGE id", () => {
    for (const id of Object.keys(LINKAGE)) {
      expect(assertCookLinkage(id)).toBe(LINKAGE[id]);
    }
    validateCookScope(Object.keys(LINKAGE));
    validateCookScope([]);
  });

  test("cook gate FAILS on every out-of-scope id (M0 acceptance)", () => {
    for (const id of OUT_OF_SCOPE_IDS) {
      let err: unknown = null;
      try {
        assertCookLinkage(id);
      } catch (e) {
        err = e;
      }
      expect(err instanceof CookScopeError).toBe(true);
      expect((err as CookScopeError).scopeClass).toBe("out-of-scope");
      expect((err as CookScopeError).linkageId).toBe(id);
    }
  });

  test("cook gate FAILS on unknown ids and on observed mixed ref sets", () => {
    let unknown: unknown = null;
    try {
      assertCookLinkage("__not_a_linkage__");
    } catch (e) {
      unknown = e;
    }
    expect(unknown instanceof CookScopeError).toBe(true);
    expect((unknown as CookScopeError).scopeClass).toBe("unknown");
    // The observed positional static set contains out-of-scope spawns
    // (event/maku/toujou...), so cooking it raw must fail; cooking the
    // in-scope projection must pass.
    const observed = inv.attachMovieStatic.map((a) => a.id);
    expect(observed.includes("maku")).toBe(true);
    let mixed: unknown = null;
    try {
      validateCookScope(observed);
    } catch (e) {
      mixed = e;
    }
    expect(mixed instanceof CookScopeError).toBe(true);
    validateCookScope(observed.filter((id) => LINKAGE[id] !== undefined));
  });

  test("runtime gate stays fail-soft (undefined + counter, no throw)", () => {
    expect(Object.keys(unknownLinkageHits).length).toBe(0);
    for (const id of Object.keys(LINKAGE)) {
      expect(resolveLinkage(id)).toBe(LINKAGE[id]);
    }
    expect(resolveLinkage("toujouS10")).toBeUndefined();
    expect(resolveLinkage("__not_a_linkage__")).toBeUndefined();
    expect(unknownLinkageHits["toujouS10"]).toBe(1);
    expect(unknownLinkageHits["__not_a_linkage__"]).toBe(1);
  });
});

