describe("ranger M0 ignore boundaries", () => {
  test(".gitignore has narrow cook rules and no repo-global dump rules", () => {
    const ignore = read(".gitignore");
    for (const rule of [
      "tools/ranger-cook/out/**",
      "tools/ranger-cook/in/**",
      "/ffdec-out/",
      "/tools/ranger-cook/**/*.xfl",
    ]) {
      expect(ignore.includes(rule)).toBe(true);
    }
    const lines = ignore.split("\n").map((l) => l.trim());
    // Repo-global dump rules are banned: raw SWF / derived-dump ignores
    // must stay local-only (scoped to cook paths).
    for (const banned of ["*.xfl", "*.swf", "*.mp3"]) {
      expect(lines.includes(banned)).toBe(false);
    }
  });

  test("cook output is git-ignored", () => {
    let out: string | null = null;
    try {
      out = execFileSync("git", ["check-ignore", "-v", "tools/ranger-cook/out/scan.json"], {
        cwd: ROOT,
        encoding: "utf8",
      });
    } catch (e) {
      if ((e as { code?: string }).code === "ENOENT") return;
      if ((e as { status?: number }).status === 1) {
        throw new Error("tools/ranger-cook/out/ is not git-ignored");
      }
      throw e;
    }
    expect(out).not.toBeNull();
  });

  test("no raw SWF or derived dumps inside tracked app paths", () => {
    const skip = new Set(["node_modules", ".git", "dist", ".cache", ".deps", ".pocket-build", "out", "in"]);
    const bad: string[] = [];
    const walkDir = (dir: string): void => {
      for (const name of readdirSync(dir)) {
        if (skip.has(name)) continue;
        const p = join(dir, name);
        if (statSync(p).isDirectory()) {
          if (dir === ROOT && name === "tools") {
            // tools/ may hold ignored cook output; still walk for *.swf.
          }
          walkDir(p);
        } else if (/\.swf$/i.test(name)) {
          bad.push(p);
        }
      }
    };
    for (const d of ["apps", "tools", "tests"]) walkDir(join(ROOT, d));
    for (const name of readdirSync(ROOT)) {
      if (/\.swf$/i.test(name)) bad.push(join(ROOT, name));
    }
    expect(bad).toEqual([]);
    const tracked = git(["ls-files", "*.swf", "*.xfl"]);
    if (tracked === null) return; // no git in this env — fs walk above still ran
    expect(tracked.trim()).toBe("");
  });
});
